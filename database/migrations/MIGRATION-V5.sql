   confidence, source, created_at, updated_at)
SELECT year, make, make_normalized, model, model_normalized, status, battery_sizes,
       confidence, 'catalogue',
       strftime('%Y-%m-%dT%H:%M:%fZ', 'now'),
       strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
FROM ranked
WHERE row_rank = 1;

