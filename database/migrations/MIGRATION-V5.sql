-- Expand the range rules to one authoritative row per exact model year.
-- Where the old JSON contained an explicit rule plus a broad fallback,
-- the earliest source rule wins, exactly matching the old JavaScript .find() behaviour.
WITH RECURSIVE expanded AS (
  SELECT source_order, make, make_normalized, model, model_normalized,
         year_from AS year, year_to, battery_sizes, status, confidence
  FROM vehicle_rule_seed_v5
  UNION ALL
  SELECT source_order, make, make_normalized, model, model_normalized,
         year + 1, year_to, battery_sizes, status, confidence
  FROM expanded
  WHERE year < year_to
),
ranked AS (
  SELECT *,
         ROW_NUMBER() OVER (
           PARTITION BY year, make_normalized, model_normalized
           ORDER BY source_order ASC
         ) AS row_rank
  FROM expanded
)
INSERT INTO vehicles_v5
